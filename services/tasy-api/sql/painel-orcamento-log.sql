-- Estado inicial dos orçamentos enviados pelo painel. Não retroativo.
CREATE TABLE TASY."AEBMG_PAINEL_ORÇAMENTO_LOG" (
  NR_ORCAMENTO NUMBER NOT NULL,
  ID_PORTAL VARCHAR2(36) NOT NULL,
  ID_USUARIO_PORTAL VARCHAR2(36) NOT NULL,
  NM_USUARIO VARCHAR2(128) NOT NULL,
  CD_ESTABELECIMENTO NUMBER NOT NULL,
  CD_PERFIL NUMBER NOT NULL,
  DT_REGISTRO TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  HASH_CONTEUDO VARCHAR2(64) NOT NULL,
  SNAPSHOT_PORTAL CLOB NOT NULL,
  CABECALHO_TASY CLOB NOT NULL,
  PROCEDIMENTOS_TASY CLOB NOT NULL,
  MATERIAIS_TASY CLOB NOT NULL,
  CONSTRAINT AEBMG_PAINEL_ORC_LOG_PK PRIMARY KEY (NR_ORCAMENTO),
  CONSTRAINT AEBMG_PAINEL_ORC_LOG_UK UNIQUE (ID_PORTAL),
  CONSTRAINT AEBMG_PAINEL_ORC_LOG_J1 CHECK (SNAPSHOT_PORTAL IS JSON),
  CONSTRAINT AEBMG_PAINEL_ORC_LOG_J2 CHECK (CABECALHO_TASY IS JSON),
  CONSTRAINT AEBMG_PAINEL_ORC_LOG_J3 CHECK (PROCEDIMENTOS_TASY IS JSON),
  CONSTRAINT AEBMG_PAINEL_ORC_LOG_J4 CHECK (MATERIAIS_TASY IS JSON)
)
/
-- Sem FK: preservar a evidência mesmo se o orçamento original for excluído.
CREATE OR REPLACE TRIGGER TASY.AEBMG_PAINEL_ORC_LOG_IMUTAVEL
BEFORE UPDATE OR DELETE ON TASY."AEBMG_PAINEL_ORÇAMENTO_LOG"
BEGIN
  RAISE_APPLICATION_ERROR(-20071, 'O log inicial do orçamento não pode ser alterado ou excluído.');
END;
/
